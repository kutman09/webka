export const TIMELINE_KEYS = Object.keys(DESKTOP[0]);

const smooth = (x) => x * x * (3 - 2 * x);

/** Sample the keyframes at timeline value t. Writes into `out` to avoid allocations. */
export function sampleTimeline(t, portrait, out = {}) {
  const frames = portrait ? MOBILE : DESKTOP;
  const max = frames.length - 1;
  const clamped = Math.min(Math.max(t, 0), max);
  const index = Math.min(Math.floor(clamped), max - 1);
  const f = smooth(clamped - index);
  const a = frames[index];
  const b = frames[index + 1];
  for (const key of TIMELINE_KEYS) out[key] = a[key] + (b[key] - a[key]) * f;
  return out;
}
